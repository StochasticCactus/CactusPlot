# Writes the Homebrew cask for a release into a checkout of the tap repository.
#
#   packaging/homebrew/update-tap.sh VERSION DMG TAP_DIR [OWNER/REPO]
#
# VERSION is e.g. 0.9.0 (no "v"), DMG the released CactusPlot-macOS-universal.dmg (only its
# checksum is used) and TAP_DIR a clone of <owner>/homebrew-tap. Users then install with
#   brew install --cask <owner>/tap/cactusplot
set -euo pipefail

if [ $# -lt 3 ]; then
    echo "usage: $0 VERSION DMG TAP_DIR [OWNER/REPO]" >&2
    exit 2
fi
version=${1#v}
dmg=$2
tap=$3
repo=${4:-StochasticCactus/CactusPlot}
here=$(cd "$(dirname "$0")" && pwd)

sha=$(sha256sum "$dmg" | cut -d' ' -f1)
mkdir -p "$tap/Casks"
{
    echo "# Generated by the release workflow of https://github.com/$repo. Do not edit."
    sed -e '/^cask /,$!d' -e "s|@VERSION@|$version|g" -e "s|@SHA256@|$sha|g" -e "s|@REPO@|$repo|g" \
        "$here/cactusplot.rb.in"
} > "$tap/Casks/cactusplot.rb"

if [ ! -f "$tap/README.md" ]; then
    owner=${repo%%/*}
    cat > "$tap/README.md" <<EOF
# Homebrew tap for CactusPlot

\`\`\`bash
brew install --cask ${owner,,}/tap/cactusplot
\`\`\`

This installs the CactusPlot app in /Applications and the \`cactusplot\` and \`cactusbat\`
commands. Update with \`brew upgrade --cask cactusplot\`.

The cask is updated automatically by the release workflow of
[$repo](https://github.com/$repo); do not edit it here.
EOF
fi
echo "Casks/cactusplot.rb: version $version, sha256 $sha"
